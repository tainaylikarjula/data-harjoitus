# Pieni datankäsittelyharjoitus

# Lista numeroita
luvut = [12, 5, 8, 19, 3, 14]

# Lasketaan keskiarvo
keskiarvo = sum(luvut) / len(luvut)

# Etsitään pienin ja suurin arvo
pienin = min(luvut)
suurin = max(luvut)

print("Luvut:", luvut)
print("Keskiarvo:", keskiarvo)
print("Pienin arvo:", pienin)
print("Suurin arvo:", suurin)
